package tools.vitruv.methodologisttemplate.vsum;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Stream;

import org.eclipse.emf.common.util.URI;

import tools.vitruv.framework.vsum.internal.InternalVirtualModel;

/**
 * Case Study 2: snapshots of a complete V-SUM state (all product and validation-environment models, the
 * correspondence model and the V-SUM metadata).
 *
 * <p>A snapshot is the content of a V-SUM storage folder in which the absolute storage-folder URI is replaced by
 * {@value #STORAGE_FOLDER_PLACEHOLDER}, so that it can be restored into any folder. Each scenario test loads exactly
 * one snapshot - the state before the scenario ("snapshot 0") - and performs all scenario steps in code.
 *
 * <p>The snapshots under {@code src/test/resources/casestudy2/snapshots} are generated by {@link #main(String[])}
 * from {@link CaseStudy2Scenarios}; regenerate them after changing the metamodels, the reactions or the instances.
 */
public final class CaseStudy2Snapshots {

  /** Placeholder for the absolute storage-folder URI inside a snapshot. */
  public static final String STORAGE_FOLDER_PLACEHOLDER = "${VSUM_STORAGE_FOLDER}";

  /** Scenario 1 initial state: product generation Gn-1 and the validation environment for Gn-1. */
  public static final String SCENARIO1_INITIAL_STATE = "scenario1-initial-state-gn-1";

  /** Scenario 2 initial state: product generations Gn-1 and Gn and the validation environment after scenario 1. */
  public static final String SCENARIO2_INITIAL_STATE = "scenario2-initial-state-gn";

  /** Default location of the snapshots, relative to the {@code vsum} module. */
  public static final Path DEFAULT_SNAPSHOT_ROOT = Path.of("src", "test", "resources", "casestudy2", "snapshots");

  private CaseStudy2Snapshots() {
  }

  /** Restores a snapshot into the (empty) storage folder and builds the V-SUM on top of it. */
  public static InternalVirtualModel load(Path snapshotFolder, Path storageFolder) {
    copy(snapshotFolder, storageFolder, STORAGE_FOLDER_PLACEHOLDER, storageFolderUri(storageFolder));
    // the stored correspondences are typed by the Reactions correspondence metamodel
    tools.vitruv.dsls.reactions.runtime.correspondence.CorrespondencePackage.eINSTANCE.getClass();
    return CaseStudy2Vsum.createVirtualModel(storageFolder);
  }

  /** Writes the current content of a V-SUM storage folder as snapshot. */
  public static void export(Path storageFolder, Path snapshotFolder) {
    copy(storageFolder, snapshotFolder, storageFolderUri(storageFolder), STORAGE_FOLDER_PLACEHOLDER);
  }

  private static String storageFolderUri(Path storageFolder) {
    return URI.createFileURI(storageFolder.toAbsolutePath().normalize().toString()).toString();
  }

  private static void copy(Path from, Path to, String search, String replacement) {
    try (Stream<Path> files = Files.walk(from)) {
      for (Path source : files.toList()) {
        Path target = to.resolve(from.relativize(source).toString());
        if (Files.isDirectory(source)) {
          Files.createDirectories(target);
        } else {
          Files.createDirectories(target.getParent());
          String content = Files.readString(source, StandardCharsets.UTF_8);
          Files.writeString(target, content.replace(search, replacement), StandardCharsets.UTF_8);
        }
      }
    } catch (IOException e) {
      throw new UncheckedIOException("Could not copy V-SUM state from " + from + " to " + to, e);
    }
  }

  /**
   * Generates the snapshots of Case Study 2.
   *
   * @param args optional target folder (default {@link #DEFAULT_SNAPSHOT_ROOT})
   */
  public static void main(String[] args) throws IOException {
    Path snapshotRoot = args.length > 0 ? Path.of(args[0]) : DEFAULT_SNAPSHOT_ROOT;
    Path storage = Files.createTempDirectory("casestudy2-snapshot").resolve("vsum");
    Files.createDirectories(storage);
    InternalVirtualModel vsum = CaseStudy2Vsum.createVirtualModel(storage);

    CaseStudy2Scenarios.initialiseGnMinus1(vsum, storage);
    exportClean(storage, snapshotRoot.resolve(SCENARIO1_INITIAL_STATE));

    CaseStudy2Scenarios.runScenario1(vsum, storage);
    exportClean(storage, snapshotRoot.resolve(SCENARIO2_INITIAL_STATE));

    vsum.dispose();
    System.out.println("Snapshots written to " + snapshotRoot.toAbsolutePath());
  }

  private static void exportClean(Path storage, Path snapshotFolder) throws IOException {
    if (Files.exists(snapshotFolder)) {
      try (Stream<Path> files = Files.walk(snapshotFolder)) {
        for (Path p : files.sorted((a, b) -> b.compareTo(a)).toList()) {
          Files.delete(p);
        }
      }
    }
    export(storage, snapshotFolder);
    List<String> content;
    try (Stream<Path> files = Files.list(snapshotFolder)) {
      content = files.map(p -> p.getFileName().toString()).sorted().toList();
    }
    System.out.println(snapshotFolder + ": " + content);
  }
}
